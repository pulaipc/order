#!/usr/bin/env python3
"""Loopback bridge from admin.html to copygame.sh / push_gamelist.sh.

SteamOS/Linux equivalent of install-server.ps1. Uses only Python 3's standard
library and runs one local job at a time. The helper listens on 127.0.0.1.
"""

from __future__ import annotations

import argparse
import datetime as dt
import hmac
import json
import os
from pathlib import Path
import re
import secrets
import shutil
import signal
import subprocess
import sys
import threading
import time
from http.server import BaseHTTPRequestHandler, ThreadingHTTPServer
from urllib.parse import urlparse


SCRIPT_DIR = Path(__file__).resolve().parent
COPY_SCRIPT = SCRIPT_DIR / "copygame.sh"
SYNC_SCRIPT = SCRIPT_DIR / "push_gamelist.sh"
TOKEN_FILE = SCRIPT_DIR / "install_server_token.txt"
READY_FILE = SCRIPT_DIR / "install-server.ready"
LOCAL_CONFIG = SCRIPT_DIR / "install_local.js"
GAMES_LIST = SCRIPT_DIR / "gameslist.js"
LIST_FILE = SCRIPT_DIR / "games_to_copy.txt"
DEFAULT_ORIGINS = "https://pulaipc.github.io,http://127.0.0.1:*,http://localhost:*"


class State:
    def __init__(self, max_lines: int = 4000) -> None:
        self.lock = threading.RLock()
        self.max_lines = max_lines
        self.lines: list[str] = []
        self.total = 0
        self.proc: subprocess.Popen[str] | None = None
        self.job_type: str | None = None
        self.started_at: str | None = None
        self.last_exit: int | str | None = None
        self.cancelled = False

    def add_line(self, text: str) -> None:
        with self.lock:
            self.lines.append(text)
            self.total += 1
            if len(self.lines) > self.max_lines:
                removed = len(self.lines) - self.max_lines
                del self.lines[:removed]

    def snapshot(self) -> dict:
        with self.lock:
            proc = self.proc
            # Keep reporting running until the reader thread has drained the
            # final output and recorded the child's exit code.
            running = proc is not None
            return {
                "running": running,
                "pause": False,
                "startedAt": self.started_at,
                "lastExit": self.last_exit,
                "total": self.total,
                "lines": list(self.lines),
                "platform": "linux",
                "lastSync": read_last_sync(),
            }


STATE = State()
TOKEN = ""
PORT = 8787
ALLOWED_ORIGINS: list[str] = []
ADMIN_PAGE_PATH = "admin.html"
QUIET = False


def log(text: str) -> None:
    stamp = dt.datetime.now().astimezone().strftime("%Y-%m-%d %H:%M:%S")
    try:
        log_path = SCRIPT_DIR / "install-server.log"
        if log_path.exists() and log_path.stat().st_size > 1024 * 1024:
            old_path = log_path.with_suffix(log_path.suffix + ".old")
            try:
                old_path.unlink(missing_ok=True)
                os.replace(log_path, old_path)
            except OSError:
                pass
        with log_path.open("a", encoding="utf-8") as stream:
            stream.write(f"{stamp}  {text}\n")
    except OSError:
        pass
    if not QUIET:
        print(text, flush=True)


def read_last_sync() -> str | None:
    try:
        text = GAMES_LIST.read_text(encoding="utf-8")
    except OSError:
        return None
    match = re.search(r"gamesLastSync\s*=\s*['\"]([^'\"]+)['\"]", text)
    return match.group(1) if match else None


def allowed_origin(origin: str) -> bool:
    value = origin.strip().lower().rstrip("/")
    if not value:
        return False
    for item in ALLOWED_ORIGINS:
        pattern = item.strip().lower().rstrip("/")
        if pattern.endswith("*"):
            if value.startswith(pattern[:-1]):
                return True
        elif value == pattern:
            return True
    return False


def load_token() -> str:
    try:
        token = TOKEN_FILE.read_text(encoding="ascii").splitlines()[0].strip()
    except (OSError, IndexError, UnicodeError):
        token = ""
    if not re.fullmatch(r"[0-9a-f]{48}", token):
        token = secrets.token_hex(24)
        TOKEN_FILE.write_text(token + "\n", encoding="ascii")
        try:
            TOKEN_FILE.chmod(0o600)
        except OSError:
            pass
        log(f"Generated a new token in {TOKEN_FILE}")
    return token


def write_local_config(port: int, token: str) -> None:
    LOCAL_CONFIG.write_text(
        "// Generated by install-server.py. Not committed (.gitignore).\n"
        f"window.INSTALL_LOCAL = {{ url: 'http://127.0.0.1:{port}', token: '{token}' }};\n",
        encoding="utf-8",
    )
    try:
        LOCAL_CONFIG.chmod(0o600)
    except OSError:
        pass


def spawn_job(command: list[str], kind: str, busy_error: str = "a copy or sync is already running") -> dict:
    with STATE.lock:
        existing = STATE.proc
        if existing is not None:
            return {"ok": False, "error": busy_error}

        STATE.lines.clear()
        STATE.total = 0
        STATE.last_exit = None
        STATE.started_at = dt.datetime.now().astimezone().isoformat(timespec="seconds")
        STATE.cancelled = False
        STATE.job_type = kind
        STATE.add_line(f"=== {kind} started {dt.datetime.now().astimezone().strftime('%H:%M:%S')} ===")

        env = os.environ.copy()
        env.setdefault("PYTHONIOENCODING", "utf-8")
        try:
            proc = subprocess.Popen(
                command,
                cwd=SCRIPT_DIR,
                stdin=subprocess.DEVNULL,
                stdout=subprocess.PIPE,
                stderr=subprocess.STDOUT,
                text=True,
                encoding="utf-8",
                errors="replace",
                bufsize=1,
                start_new_session=True,
                env=env,
            )
        except OSError as exc:
            STATE.job_type = None
            STATE.last_exit = 1
            STATE.add_line(f"! Could not start {kind}: {exc}")
            return {"ok": False, "error": str(exc)}
        STATE.proc = proc
        STATE.add_line("> " + " ".join(command))
        threading.Thread(target=pump_job, args=(proc,), daemon=True).start()
        return {"ok": True, "started": True}


def pump_job(proc: subprocess.Popen[str]) -> None:
    try:
        assert proc.stdout is not None
        for line in proc.stdout:
            STATE.add_line(line.rstrip("\r\n"))
        code = proc.wait()
    except Exception as exc:  # keep the HTTP helper alive if a child pipe fails
        STATE.add_line(f"! Error reading helper output: {exc}")
        try:
            code = proc.wait(timeout=2)
        except Exception:
            code = 1
    with STATE.lock:
        STATE.last_exit = "cancelled" if STATE.cancelled else code
        kind = STATE.job_type or "job"
        STATE.add_line(f"=== {kind} finished (exit {STATE.last_exit}) at {dt.datetime.now().astimezone().strftime('%H:%M:%S')} ===")
        STATE.proc = None
        STATE.job_type = None
        STATE.cancelled = False


def start_copy(body: dict) -> dict:
    games = body.get("games") or []
    if not isinstance(games, list) or any(not isinstance(name, str) for name in games):
        return {"ok": False, "error": "games must be an array of names"}
    if not games:
        return {"ok": False, "error": "no games given"}
    if len(games) > 1000 or any(len(name) > 1024 for name in games):
        return {"ok": False, "error": "game list is too large"}
    if not COPY_SCRIPT.is_file():
        return {"ok": False, "error": "copygame.sh not found"}
    bash = shutil.which("bash")
    if not bash:
        return {"ok": False, "error": "bash not found; install bash on SteamOS"}
    clean = [re.sub(r"[\r\n]+", " ", name).strip() for name in games]
    command = [bash, str(COPY_SCRIPT), "--no-pause"]
    essentials_only = bool(body.get("essentialsOnly"))
    if essentials_only:
        command.append("--essentials-only")
    elif body.get("essentials", True):
        command.append("--essentials")
    else:
        command.append("--skip-essentials")
    if body.get("dryRun"):
        command.append("--dry-run")
    with STATE.lock:
        if STATE.proc is not None:
            return {"ok": False, "error": "a copy or sync is already running"}
        LIST_FILE.write_text("".join(name + "\n" for name in clean), encoding="utf-8")
        return spawn_job(command, "install")


def start_sync() -> dict:
    if not SYNC_SCRIPT.is_file():
        return {"ok": False, "error": "push_gamelist.sh not found"}
    bash = shutil.which("bash")
    if not bash:
        return {"ok": False, "error": "bash not found; install bash on SteamOS"}
    # Match push_gamelist.ps1: the sync publishes by default. The standalone
    # script still offers --local-only for an intentional non-publishing run.
    return spawn_job(
        [bash, str(SYNC_SCRIPT)],
        "game-list sync",
        busy_error="Helper is busy; wait for the active job to finish before syncing.",
    )


class Server(ThreadingHTTPServer):
    daemon_threads = True
    allow_reuse_address = True


class Handler(BaseHTTPRequestHandler):
    server_version = "PulaiInstallHelper/1.0"

    def log_message(self, fmt: str, *args) -> None:
        log("HTTP " + (fmt % args))

    def cors_headers(self) -> None:
        origin = self.headers.get("Origin")
        self.send_header("Access-Control-Allow-Origin", origin if origin else "*")
        self.send_header("Vary", "Origin")
        self.send_header("Access-Control-Allow-Headers", "content-type, x-install-token, x-admin-page")
        self.send_header("Access-Control-Allow-Methods", "GET, POST, OPTIONS")
        self.send_header("Access-Control-Allow-Private-Network", "true")
        self.send_header("X-Content-Type-Options", "nosniff")

    def send_json(self, obj: dict, status: int = 200) -> None:
        data = json.dumps(obj, ensure_ascii=False, separators=(",", ":")).encode("utf-8")
        self.send_response(status)
        self.send_header("Content-Type", "application/json; charset=utf-8")
        self.send_header("Content-Length", str(len(data)))
        self.send_header("Cache-Control", "no-store")
        self.cors_headers()
        self.end_headers()
        self.wfile.write(data)

    def do_OPTIONS(self) -> None:  # noqa: N802
        self.send_json({"ok": True})

    def authorised(self) -> bool:
        given = self.headers.get("X-Install-Token", "")
        return bool(given) and hmac.compare_digest(given.encode(), TOKEN.encode())

    def read_json(self) -> dict | None:
        try:
            length = int(self.headers.get("Content-Length", "0"))
        except ValueError:
            return None
        if length < 0 or length > 1_000_000:
            return None
        try:
            body = json.loads(self.rfile.read(length).decode("utf-8"))
        except (UnicodeDecodeError, json.JSONDecodeError):
            return None
        return body if isinstance(body, dict) else None

    def do_GET(self) -> None:  # noqa: N802
        path = urlparse(self.path).path.rstrip("/").lower()
        if path == "/config":
            origin = self.headers.get("Origin", "")
            referer = self.headers.get("Referer", "")
            admin_page = self.headers.get("X-Admin-Page", "")
            page_ok = not ADMIN_PAGE_PATH or ADMIN_PAGE_PATH.lower() in referer.lower() or ADMIN_PAGE_PATH.lower() in admin_page.lower()
            if not allowed_origin(origin) or not page_ok:
                log(f"GET /config denied origin={origin or '(none)'}")
                self.send_json({"ok": False, "error": "origin or page not allowed"}, 403)
                return
            self.send_json({"ok": True, "url": f"http://127.0.0.1:{PORT}", "token": TOKEN, "port": PORT})
            return
        if path == "/health":
            self.send_json({"ok": True, "script": str(COPY_SCRIPT), "platform": "linux"})
            return
        if not self.authorised():
            self.send_json({"ok": False, "error": "bad or missing token"}, 401)
            return
        if path == "/status":
            self.send_json(STATE.snapshot())
            return
        self.send_json({"ok": False, "error": "unknown endpoint"}, 404)

    def do_POST(self) -> None:  # noqa: N802
        path = urlparse(self.path).path.rstrip("/").lower()
        if not self.authorised():
            self.send_json({"ok": False, "error": "bad or missing token"}, 401)
            return
        if path == "/install":
            body = self.read_json()
            if body is None:
                self.send_json({"ok": False, "error": "invalid or empty JSON body"}, 400)
                return
            result = start_copy(body)
            self.send_json(result, 200 if result.get("ok") else 409)
            return
        if path == "/push-gamelist":
            result = start_sync()
            self.send_json(result, 200 if result.get("ok") else 409)
            return
        if path == "/cancel":
            with STATE.lock:
                proc = STATE.proc
                if proc is None:
                    self.send_json({"ok": False, "error": "nothing running"}, 409)
                    return
                if proc.poll() is not None:
                    self.send_json({"ok": False, "error": "job is finishing; wait for its final output"}, 409)
                    return
                STATE.cancelled = True
                try:
                    os.killpg(proc.pid, signal.SIGTERM)
                except (ProcessLookupError, PermissionError):
                    proc.terminate()
            threading.Thread(target=kill_if_still_running, args=(proc,), daemon=True).start()
            STATE.add_line("=== stopped from the admin page ===")
            self.send_json({"ok": True, "cancelled": True})
            return
        self.send_json({"ok": False, "error": "unknown endpoint"}, 404)


def kill_if_still_running(proc: subprocess.Popen[str]) -> None:
    try:
        proc.wait(timeout=3)
    except subprocess.TimeoutExpired:
        try:
            os.killpg(proc.pid, signal.SIGKILL)
        except (ProcessLookupError, PermissionError):
            proc.kill()


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--port", type=int, default=8787)
    parser.add_argument("--allowed-origin", default=DEFAULT_ORIGINS)
    parser.add_argument("--admin-page-path", default="admin.html")
    parser.add_argument("--max-log-lines", type=int, default=4000)
    parser.add_argument("--quiet", action="store_true")
    return parser.parse_args()


def main() -> int:
    global TOKEN, PORT, ALLOWED_ORIGINS, ADMIN_PAGE_PATH, QUIET, STATE
    args = parse_args()
    QUIET = args.quiet
    STATE = State(max(100, min(args.max_log_lines, 20_000)))
    if not COPY_SCRIPT.is_file():
        print(f"copygame.sh not found next to this helper: {COPY_SCRIPT}", file=sys.stderr)
        return 1
    if args.port < 1 or args.port > 65531:
        print("Port must be between 1 and 65531", file=sys.stderr)
        return 2
    TOKEN = load_token()
    ALLOWED_ORIGINS = [item.strip() for item in args.allowed_origin.split(",") if item.strip()]
    ADMIN_PAGE_PATH = args.admin_page_path

    server = None
    last_error = None
    for port in range(args.port, args.port + 5):
        try:
            server = Server(("127.0.0.1", port), Handler)
            PORT = port
            break
        except OSError as exc:
            last_error = exc
    if server is None:
        print(f"Could not listen on ports {args.port}-{args.port + 4}: {last_error}", file=sys.stderr)
        return 1

    try:
        READY_FILE.unlink()
    except OSError:
        pass
    write_local_config(PORT, TOKEN)
    READY_FILE.write_text(f"{dt.datetime.now().astimezone().isoformat()}\nhttp://127.0.0.1:{PORT}/\npid={os.getpid()}\n", encoding="utf-8")
    log("")
    log("  Pulai SteamOS/Linux install helper")
    log(f"  Listening on http://127.0.0.1:{PORT}/")
    log(f"  Copy script: {COPY_SCRIPT}")
    log(f"  Game-list sync: {SYNC_SCRIPT} (commits and pushes generated catalog)")
    log(f"  Wrote: {LOCAL_CONFIG}")
    log(f"  Log: {SCRIPT_DIR / 'install-server.log'}")
    log("  Ctrl+C to stop.")
    try:
        server.serve_forever(poll_interval=0.25)
    except KeyboardInterrupt:
        pass
    finally:
        server.server_close()
        try:
            READY_FILE.unlink()
        except OSError:
            pass
        log("Helper stopped.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
